#!/usr/bin/env node
/**
 * Generate Quick Look Swift config, Info.plist, and preview-registry.json.
 *
 * Usage: node scripts/generate-quicklook-config.js
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  buildPreviewRegistry,
  getQuickLookMimeTypes,
  listDeclaredQuickLookUtis,
  listFileAssociationExtensions,
  listQuickLookActiveExtensions,
} from '../config/resolvePlatformCapability.js';
import {
  getQuickLookUnionLayoutKeys,
  listQuickLookUnionExtensions,
  listQuickLookUnionUtis,
} from '../config/resolveQuickLookManifest.js';
import { PREVIEW_LAYOUTS } from '@blendviewer/vision-scope/formats';

const __dirname = dirname(fileURLToPath(import.meta.url));
const APP_DIR = join(__dirname, '..');
const QL_DIR = join(APP_DIR, 'quicklook', 'VisionScopeQuickLook');
const SWIFT_OUT = join(QL_DIR, 'GeneratedQuickLookConfig.swift');
const PLIST_PATH = join(QL_DIR, 'Info.plist');
const REGISTRY_OUT = join(APP_DIR, 'public', 'preview-registry.json');
const TAURI_CONF_PATH = join(APP_DIR, 'src-tauri', 'tauri.conf.json');

/** @type {Record<string, string>} */
const LAYOUT_KEY_TO_SWIFT = {
  spatial_3d: 'threeD',
  spatial_cad: 'cad',
  point_cloud: 'pointCloud',
  texture: 'texture',
  document: 'document',
  tabular: 'document',
  presentation: 'document',
  archive: 'document',
  image: 'document',
  media: 'document',
};

/** @type {Record<string, keyof typeof PREVIEW_LAYOUTS>} */
const SWIFT_GROUP_TO_LAYOUT_KEY = {
  threeD: 'spatial_3d',
  cad: 'spatial_cad',
  pointCloud: 'point_cloud',
  texture: 'texture',
  document: 'document',
};

function swiftStringLiteral(value) {
  return `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

function generateSwift() {
  const unionExtensions = listQuickLookUnionExtensions();
  const mimeTypes = getQuickLookMimeTypes();
  const layoutKeys = getQuickLookUnionLayoutKeys();

  /** @type {Record<string, string>} */
  const extToGroup = {};
  for (const ext of unionExtensions) {
    const layoutKey = layoutKeys[ext] ?? 'document';
    extToGroup[ext] = LAYOUT_KEY_TO_SWIFT[layoutKey] ?? 'threeD';
  }

  const extGroupCases = Object.entries(extToGroup)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([ext, group]) => `        case ${swiftStringLiteral(ext)}: return .${group}`)
    .join('\n');

  const mimeEntries = Object.entries(mimeTypes)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([ext, mime]) => `        ${swiftStringLiteral(ext)}: ${swiftStringLiteral(mime)}`)
    .join(',\n');

  const layoutSizeCases = Object.entries(SWIFT_GROUP_TO_LAYOUT_KEY)
    .map(([swiftGroup, layoutKey]) => {
      const layout = PREVIEW_LAYOUTS[layoutKey];
      return `            case .${swiftGroup}:\n                return NSSize(width: ${layout.width}, height: ${layout.height})`;
    })
    .join('\n');

  const unionExtLines = unionExtensions
    .map((ext) => `        ${swiftStringLiteral(ext)},`)
    .join('\n');

  return `// Generated by scripts/generate-quicklook-config.js — do not edit manually.

import Foundation

/// Finder Quick Look union + layout config from config/quickLookUnion.js
enum GeneratedQuickLookConfig {
    /// Maximal Finder admission set (macOS routes by UTI → calls this extension).
    static let unionExtensions: Set<String> = [
${unionExtLines}
    ]

    static let previewMimeTypes: [String: String] = [
${mimeEntries}
    ]

    /// Preview layout grouping for preferredContentSize
    enum PreviewLayoutGroup {
        case threeD
        case cad
        case pointCloud
        case texture
        case document

        var preferredSize: NSSize {
            switch self {
${layoutSizeCases}
            }
        }

        static func forExtension(_ ext: String) -> PreviewLayoutGroup {
            switch ext {
${extGroupCases}
            default:
                return .threeD
            }
        }
    }
}
`;
}

function xmlIndent(level) {
  return '\t'.repeat(level);
}

function generateUtiDeclaration(entry) {
  const conformsLines = entry.conformsTo
    .map((item) => `${xmlIndent(4)}<string>${item}</string>`)
    .join('\n');
  const extLines = entry.extensions
    .map((ext) => `${xmlIndent(5)}<string>${ext}</string>`)
    .join('\n');

  return `${xmlIndent(2)}<dict>
${xmlIndent(3)}<key>UTTypeConformsTo</key>
${xmlIndent(3)}<array>
${conformsLines}
${xmlIndent(3)}</array>
${xmlIndent(3)}<key>UTTypeDescription</key>
${xmlIndent(3)}<string>${entry.description}</string>
${xmlIndent(3)}<key>UTTypeIdentifier</key>
${xmlIndent(3)}<string>${entry.uti}</string>
${xmlIndent(3)}<key>UTTypeTagSpecification</key>
${xmlIndent(3)}<dict>
${xmlIndent(4)}<key>public.filename-extension</key>
${xmlIndent(4)}<array>
${extLines}
${xmlIndent(4)}</array>
${xmlIndent(3)}</dict>
${xmlIndent(2)}</dict>`;
}

function generateUtImportedTypeDeclarations() {
  const entries = listDeclaredQuickLookUtis();
  if (entries.length === 0) {
    return '';
  }
  return entries.map(generateUtiDeclaration).join('\n');
}

function generateQlSupportedContentTypes() {
  return listQuickLookUnionUtis()
    .map((uti) => `${xmlIndent(4)}<string>${uti}</string>`)
    .join('\n');
}

function generateInfoPlist() {
  const utiBlock = generateUtImportedTypeDeclarations();
  const qlTypes = generateQlSupportedContentTypes();

  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleDevelopmentRegion</key>
	<string>en</string>
	<key>CFBundleDisplayName</key>
	<string>VisionScope Quick Look</string>
	<key>CFBundleExecutable</key>
	<string>$(EXECUTABLE_NAME)</string>
	<key>CFBundleIdentifier</key>
	<string>$(PRODUCT_BUNDLE_IDENTIFIER)</string>
	<key>CFBundleInfoDictionaryVersion</key>
	<string>6.0</string>
	<key>CFBundleName</key>
	<string>$(PRODUCT_NAME)</string>
	<key>CFBundlePackageType</key>
	<string>XPC!</string>
	<key>CFBundleShortVersionString</key>
	<string>0.1.0</string>
	<key>CFBundleVersion</key>
	<string>1</string>
	<key>UTImportedTypeDeclarations</key>
	<array>
${utiBlock}
	</array>
	<key>NSExtension</key>
	<dict>
		<key>NSExtensionAttributes</key>
		<dict>
			<key>QLIsDataBasedPreview</key>
			<false/>
			<key>QLSupportedContentTypes</key>
			<array>
${qlTypes}
			</array>
		</dict>
		<key>NSExtensionPointIdentifier</key>
		<string>com.apple.quicklook.preview</string>
		<key>NSExtensionPrincipalClass</key>
		<string>$(PRODUCT_MODULE_NAME).PreviewViewController</string>
	</dict>
</dict>
</plist>
`;
}

function patchTauriFileAssociations() {
  const conf = JSON.parse(readFileSync(TAURI_CONF_PATH, 'utf8'));
  const extensions = listFileAssociationExtensions();

  if (!conf.bundle?.fileAssociations?.length) {
    throw new Error('tauri.conf.json: expected bundle.fileAssociations[0]');
  }

  conf.bundle.fileAssociations[0].ext = extensions;
  writeFileSync(TAURI_CONF_PATH, `${JSON.stringify(conf, null, 2)}\n`, 'utf8');
  console.log(`Patched ${TAURI_CONF_PATH} (${extensions.length} extensions)`);
}

function main() {
  const swift = generateSwift();
  writeFileSync(SWIFT_OUT, swift, 'utf8');
  console.log(`Wrote ${SWIFT_OUT}`);

  const plist = generateInfoPlist();
  writeFileSync(PLIST_PATH, plist, 'utf8');
  console.log(`Wrote ${PLIST_PATH}`);

  const registry = buildPreviewRegistry();
  writeFileSync(REGISTRY_OUT, `${JSON.stringify(registry, null, 2)}\n`, 'utf8');
  console.log(`Wrote ${REGISTRY_OUT}`);

  patchTauriFileAssociations();

  const unionCount = listQuickLookUnionExtensions().length;
  const activeCount = listQuickLookActiveExtensions().length;
  const utiCount = listQuickLookUnionUtis().length;
  console.log(
    `Quick Look union: ${unionCount} extensions, ${utiCount} UTIs; active: ${activeCount}`,
  );
}

main();
